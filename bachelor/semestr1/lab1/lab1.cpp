#include <iostream>              // подключаем стандартный ввод/вывод (cin, cout)
#include <iomanip>               // подключаем манипуляторы setprecision, fixed
#include <cmath>                 // подключаем математические функции pow, powf
#include <clocale>               // подключаем setlocale для корректной кириллицы

using namespace std;             // используем стандартное пространство имён std

int main()                       // главная функция — точка входа в программу
{
    setlocale(LC_ALL, ".65001"); // включаем русскую локализацию для вывода кириллицы
    cout << fixed;                // фиксируем формат вывода чисел (без экспоненты)

    // ================= РЕШЕНИЕ 1: float через powf =================
    cout << "=== Решение 1: float (powf) ===\n";  // выводим заголовок первого решения

    float a_f1 = 100.0f, b_f1 = 0.001f;           // объявляем и инициализируем a и b типа float

    float ab_f1   = a_f1 - b_f1;                  // вычисляем (a - b) и сохраняем в промежуточную переменную
    float a4_f1   = powf(a_f1, 4.0f);             // вычисляем a^4 через powf (версия для float)
    float a3b_f1  = powf(a_f1, 3.0f) * b_f1;      // вычисляем a^3 * b
    float a2b2_f1 = powf(a_f1, 2.0f) * powf(b_f1, 2.0f); // вычисляем a^2 * b^2
    float ab3_f1  = a_f1 * powf(b_f1, 3.0f);      // вычисляем a * b^3
    float b4_f1   = powf(b_f1, 4.0f);             // вычисляем b^4

    float num1_f1  = powf(ab_f1, 4.0f);           // num1 = (a - b)^4
    float num2_f1  = a4_f1 - 4.0f * a3b_f1;       // num2 = a^4 - 4*a^3*b
    float numer_f1 = num1_f1 - num2_f1;           // числитель = num1 - num2

    float denom_f1  = 6.0f * a2b2_f1 - 4.0f * ab3_f1 + b4_f1; // знаменатель = 6a^2b^2 - 4ab^3 + b^4
    float result_f1 = numer_f1 / denom_f1;        // результат = числитель / знаменатель

    cout << setprecision(10);                     // задаём 10 знаков после запятой для вывода
    cout << "num1 (a-b)^4        = " << num1_f1   << "\n"; // выводим num1
    cout << "num2 (a^4-4a^3b)    = " << num2_f1   << "\n"; // выводим num2
    cout << "числитель           = " << numer_f1  << "\n"; // выводим числитель
    cout << "знаменатель         = " << denom_f1  << "\n"; // выводим знаменатель
    cout << "результат (float)   = " << result_f1 << "\n\n"; // выводим итоговый результат

    // ================= РЕШЕНИЕ 2: float через pow =================
    cout << "=== Решение 2: float (pow) ===\n";   // заголовок второго решения

    float a_f2 = 100.0f, b_f2 = 0.001f;           // те же входные данные типа float

    float ab_f2   = a_f2 - b_f2;                  // (a - b)
    float a4_f2   = pow(a_f2, 4.0f);              // a^4 — теперь через обычный pow (double)
    float a3b_f2  = pow(a_f2, 3.0f) * b_f2;       // a^3 * b
    float a2b2_f2 = pow(a_f2, 2.0f) * pow(b_f2, 2.0f); // a^2 * b^2
    float ab3_f2  = a_f2 * pow(b_f2, 3.0f);       // a * b^3
    float b4_f2   = pow(b_f2, 4.0f);              // b^4

    float num1_f2  = pow(ab_f2, 4.0f);            // num1 = (a - b)^4 через pow
    float num2_f2  = a4_f2 - 4.0f * a3b_f2;       // num2 = a^4 - 4a^3b
    float numer_f2 = num1_f2 - num2_f2;           // числитель

    float denom_f2  = 6.0f * a2b2_f2 - 4.0f * ab3_f2 + b4_f2; // знаменатель
    float result_f2 = numer_f2 / denom_f2;        // результат

    cout << "num1 (a-b)^4        = " << num1_f2   << "\n"; // вывод num1
    cout << "num2 (a^4-4a^3b)    = " << num2_f2   << "\n"; // вывод num2
    cout << "числитель           = " << numer_f2  << "\n"; // вывод числителя
    cout << "знаменатель         = " << denom_f2  << "\n"; // вывод знаменателя
    cout << "результат (float)   = " << result_f2 << "\n\n"; // вывод результата

    // ================= РЕШЕНИЕ 3: double через pow =================
    cout << "=== Решение 3: double (pow) ===\n";  // заголовок третьего решения

    double a_d = 100.0, b_d = 0.001;              // входные данные типа double

    double ab_d   = a_d - b_d;                    // (a - b)
    double a4_d   = pow(a_d, 4.0);                // a^4
    double a3b_d  = pow(a_d, 3.0) * b_d;          // a^3 * b
    double a2b2_d = pow(a_d, 2.0) * pow(b_d, 2.0);// a^2 * b^2
    double ab3_d  = a_d * pow(b_d, 3.0);          // a * b^3
    double b4_d   = pow(b_d, 4.0);                // b^4

    double num1_d  = pow(ab_d, 4.0);              // num1 = (a - b)^4
    double num2_d  = a4_d - 4.0 * a3b_d;          // num2 = a^4 - 4a^3b
    double numer_d = num1_d - num2_d;             // числитель

    double denom_d  = 6.0 * a2b2_d - 4.0 * ab3_d + b4_d; // знаменатель
    double result_d = numer_d / denom_d;          // результат

    cout << setprecision(15);                     // 15 знаков после запятой для double
    cout << "num1 (a-b)^4        = " << num1_d   << "\n"; // вывод num1
    cout << "num2 (a^4-4a^3b)    = " << num2_d   << "\n"; // вывод num2
    cout << "числитель           = " << numer_d  << "\n"; // вывод числителя
    cout << "знаменатель         = " << denom_d  << "\n"; // вывод знаменателя
    cout << "результат (double)  = " << result_d << "\n\n"; // вывод результата

    // ================= ЗАДАНИЕ 2 =================
    cout << "=== Задание 2 ===\n";                // заголовок второго задания

    int n, m, r;                                  // объявляем целочисленные переменные n, m, r

    // 1) n++ * m
    n = 5; m = 3;                                 // задаём начальные значения n = 5, m = 3
    r = n++ * m;                                  // постфиксный n++ возвращает 5, 5*3=15, затем n становится 6
    cout << "\n1) n++ * m\n";                    // выводим название выражения
    cout << "   результат = " << r << ", n = " << n << ", m = " << m << "\n"; // выводим r, n, m
    cout << "   Пояснение: n++ возвращает старое значение 5, 5*3=15. n становится 6.\n"; // пояснение

    // 2) n++ < m
    n = 5; m = 3;                                 // сбрасываем n = 5, m = 3
    r = n++ < m;                                  // n++ возвращает 5, сравнение 5<3 ложно -> 0, затем n=6
    cout << "\n2) n++ < m\n";                    // выводим название выражения
    cout << "   результат = " << r << " (0 = false), n = " << n << ", m = " << m << "\n"; // выводим r, n, m
    cout << "   Пояснение: n++ возвращает 5, 5<3 ложно -> 0. n становится 6.\n"; // пояснение

    // 3) m-- > m  — в C++17 порядок операндов зафиксирован (слева направо)
    n = 5; m = 3;                                 // сбрасываем n = 5, m = 3
    r = m-- > m;                                  // m-- возвращает 3, m становится 2, затем 3>2 -> 1
    cout << "\n3) m-- > m\n";                    // выводим название выражения
    cout << "   результат = " << r << " (1 = true), n = " << n << ", m = " << m << "\n"; // выводим r, n, m
    cout << "   Пояснение: m-- возвращает старое 3 и уменьшает m до 2.\n"; // первая строка пояснения
    cout << "              Затем 3 > 2 -> истина (1). m остаётся равным 2.\n"; // вторая строка пояснения

    return 0;                                     // возвращаем 0 — успешное завершение программы
}